def detect_system_language():
    """Определяет язык ОС при первом запуске: ru/uk/en."""
    try:
        lang_code, _ = locale.getdefaultlocale()
    except Exception:
        lang_code = None
    if not lang_code:
        return "en"
    lang_code = lang_code.lower()
    if lang_code.startswith("ru"):
        return "ru"
    if lang_code.startswith("uk"):
        return "uk"
    return "en"


def init_language(settings: QSettings):
    """Вызывается один раз при старте приложения."""
    global _current_lang
    saved = settings.value("app/language", None)
    if saved:
        _current_lang = saved
    else:
        _current_lang = detect_system_language()
        settings.setValue("app/language", _current_lang)


def set_language(lang: str, settings: QSettings):
    global _current_lang
    _current_lang = lang
    settings.setValue("app/language", lang)


def get_language():
    return _current_lang


def tr(text: str) -> str:
    """Возвращает перевод текста для текущего языка."""
    if _current_lang == "ru":
        return text
    table = _TRANSLATIONS.get(_current_lang, {})
    return table.get(text, text)
